// Builds the scenario bank: public/bank.js.
//   npm run scenarios                      30 per level from rules, no key needed
//   npm run scenarios -- --claude          ask Claude too (needs ANTHROPIC_API_KEY in .env.local)
//   npm run scenarios -- --per-level 50    bigger bank
//   npm run scenarios -- --fresh           start over instead of adding to the current bank
// Every scenario, whoever wrote it, must pass validation and be winnable in the simulator.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateScenario, activeFaults } from '../public/scenario.js';
import { winnable } from './lib/bots.mjs';
import { candidate, uniqueName } from './lib/procedural.mjs';

// Reads ANTHROPIC_API_KEY from .env.local if it is there. Works on any Node version, and never overrides a real environment variable.
try {
  for (const line of fs.readFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '.env.local'), 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith('#') && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
} catch { /* no .env.local: rules only */ }

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'public', 'bank.js');
const args = process.argv.slice(2);
const flag = (n) => args.includes(`--${n}`);
const val = (n, d) => (args.includes(`--${n}`) ? args[args.indexOf(`--${n}`) + 1] : d);
const PER = Number(val('per-level', 30));
const LEVELS = ['easy', 'medium', 'hard'];

async function loadBank() {
  if (flag('fresh') || !fs.existsSync(out)) return { easy: [], medium: [], hard: [] };
  const { BANK } = await import(`${out}?t=${Date.now()}`);
  return { easy: [...BANK.easy], medium: [...BANK.medium], hard: [...BANK.hard] };
}

// How often each kind may appear in a level's bank, as a share of its size, so the mix stays varied.
const QUOTA = {
  easy: { none: 1 },
  medium: { none: 0.2, leak: 0.4, thrustCap: 0.4 },
  hard: { leak: 0.38, thrustCap: 0.38, dropouts: 0.42, weakSide: 0.55 },
};
const kindsOf = (sc) => (activeFaults(sc.faults).length ? activeFaults(sc.faults) : ['none']);

function accept(level, sc, bank) {
  const v = validateScenario(sc, level);
  if (!v.ok) return { ok: false, why: v.errors.join('; ') };
  for (const k of kindsOf(v.scenario)) {
    const used = bank[level].filter((b) => kindsOf(b).includes(k)).length;
    if (used >= Math.ceil((QUOTA[level][k] ?? 0) * PER)) return { ok: false, why: `enough ${k} scenarios already` };
  }
  const seeds = new Set(bank[level].map((s) => s.seed));
  if (seeds.has(v.scenario.seed)) return { ok: false, why: 'seed already used' };
  const w = winnable(level, v.scenario);
  if (!w.ok) return { ok: false, why: `not winnable by ${w.by}` };
  const taken = new Set(bank[level].map((s) => s.name));
  const prefix = level[0];
  const id = `${prefix}-${String(bank[level].length + 1).padStart(3, '0')}`;
  return { ok: true, scenario: { ...v.scenario, id, name: uniqueName(v.scenario.name, taken) } };
}

const bank = await loadBank();
const stats = {};

for (const level of LEVELS) {
  stats[level] = { rules: 0, claude: 0, rejected: 0 };
  if (flag('claude')) {
    const { proposeScenarios, hasKey } = await import('./lib/claude.mjs');
    if (!hasKey()) { console.error('No ANTHROPIC_API_KEY. Add it to .env.local, or run without --claude.'); process.exit(1); }
    for (let round = 0; round < 8 && bank[level].length < PER; round++) {
      const r = await proposeScenarios({ level, count: 12, avoid: bank[level].map((s) => s.name) });
      for (const sc of r.scenarios) {
        if (bank[level].length >= PER) break;
        const a = accept(level, sc, bank);
        if (a.ok) { bank[level].push(a.scenario); stats[level].claude++; } else stats[level].rejected++;
      }
      console.log(`${level}: round ${round + 1} from ${r.model}: ${bank[level].length}/${PER}`);
    }
  }
  for (let i = 1; bank[level].length < PER && i < 4000; i++) {
    const a = accept(level, candidate(level, i, new Set(bank[level].map((b) => b.name))), bank);
    if (a.ok) { bank[level].push(a.scenario); stats[level].rules++; } else stats[level].rejected++;
  }
  if (bank[level].length < PER) console.error(`${level}: only ${bank[level].length} of ${PER} scenarios passed.`);
}

const text = `// Generated by scripts/generate-scenarios.mjs. Regenerate instead of editing by hand.\nexport const BANK = ${JSON.stringify(bank, null, 1)};\n`;
fs.writeFileSync(out, text);
for (const l of LEVELS) console.log(`${l}: ${bank[l].length} scenarios (${stats[l].rules} from rules, ${stats[l].claude} from Claude, ${stats[l].rejected} rejected)`);
console.log(`wrote ${out}`);
